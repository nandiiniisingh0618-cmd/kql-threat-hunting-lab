"""Generate coverage/attack-layer.json, COVERAGE.md and GAPS.md.

Coverage is derived from TEST RESULTS, never from the detection files alone. A
technique is only coloured if a detection claiming it has a test that actually
produced its required hits on real dataset events. If RESULTS.md has not been
generated yet, this refuses to guess.
"""
from __future__ import annotations

import json
import re
import sys
from datetime import UTC, datetime

from . import config
from .registry import attack_model, load_detections

LAYER_NAME = "KQL Threat-Hunting Lab"
GRADIENT = ["#d7ebff", "#1f5fa9"]


def parse_results() -> dict[str, dict]:
    """Read RESULTS.md and recover per-detection pass state and hit counts.

    RESULTS.md is generated by `make test`; parsing it keeps this tool honest -
    coverage cannot be produced without having run the tests.
    """
    path = config.REPO_ROOT / "RESULTS.md"
    if not path.exists():
        sys.exit(
            "RESULTS.md not found. Coverage is generated from test results, so run\n"
            "  python tasks.py test\n"
            "first (it needs the emulator up and data ingested)."
        )
    text = path.read_text(encoding="utf-8")
    rows: dict[str, dict] = {}
    # | Detection | Techniques | Status | TP hits | Cross-dataset | Rate | Time (s) |
    pattern = re.compile(
        r"^\|\s*(?P<name>[^|]+?)\s*\|\s*(?P<techniques>[^|]*?)\s*\|"
        r"\s*(?P<status>[^|]*?)\s*\|\s*(?P<tp>\d+)\s*\|\s*(?P<cross>\d+)\s*\|"
        r"\s*(?P<rate>[\d.]+)\s*\|\s*(?P<time>[\d.]+)\s*\|$",
        re.MULTILINE,
    )
    for match in pattern.finditer(text):
        name = match.group("name").strip()
        if name in ("Detection", "---"):
            continue
        status = match.group("status")
        rows[name] = {
            "techniques": [t.strip() for t in match.group("techniques").split(",") if t.strip()],
            "status": status,
            "passed": "pass" in status,
            "tp_hits": int(match.group("tp")),
            "cross_datasets": int(match.group("cross")),
            "fp_rate": float(match.group("rate")),
            "runtime": float(match.group("time")),
        }
    if not rows:
        sys.exit("could not parse any detection rows out of RESULTS.md")
    return rows


def main(argv: list[str] | None = None) -> int:
    argv = argv or []
    model = attack_model()
    detections = load_detections()
    results = parse_results()

    config.COVERAGE_DIR.mkdir(parents=True, exist_ok=True)

    # ---- which techniques are genuinely covered ----
    covered: dict[str, list[dict]] = {}   # technique -> passing detections
    claimed: dict[str, list[dict]] = {}   # technique -> all detections claiming it

    for detection in detections:
        result = results.get(detection["name"])
        for technique_id in detection["techniques"]:
            claimed.setdefault(technique_id, []).append(detection)
            if result and result["passed"]:
                covered.setdefault(technique_id, []).append(detection)

    max_score = max((len(v) for v in covered.values()), default=1)

    # ---- Navigator layer ----
    techniques_layer = []
    for technique_id, dets in sorted(covered.items()):
        names = ", ".join(d["name"] for d in dets)
        techniques_layer.append({
            "techniqueID": technique_id,
            "score": len(dets),
            "color": "",
            "comment": f"{len(dets)} passing detection(s): {names}",
            "enabled": True,
            "metadata": [
                {"name": "detections", "value": str(len(dets))},
                {"name": "files", "value": ", ".join(d["_rel_path"] for d in dets)},
            ],
            "showSubtechniques": False,
        })

    layer = {
        "name": LAYER_NAME,
        "versions": {"attack": model["version"], "navigator": "5.1.0", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": (
            f"Techniques with at least one PASSING real-data test in this lab. "
            f"Generated {datetime.now(UTC).strftime('%Y-%m-%d')} from RESULTS.md. "
            "Scored by number of passing detections. Coverage applies ONLY to the pinned "
            "public attack datasets in this repo, not to production telemetry."
        ),
        "filters": {"platforms": ["Windows"]},
        "sorting": 3,
        "layout": {"layout": "side", "showName": True, "showID": True},
        "hideDisabled": False,
        "techniques": techniques_layer,
        "gradient": {"colors": GRADIENT, "minValue": 0, "maxValue": max_score},
        "legendItems": [
            {"label": "1 passing detection", "color": GRADIENT[0]},
            {"label": f"{max_score} passing detections", "color": GRADIENT[1]},
        ],
        "showTacticRowBackground": True,
        "tacticRowBackground": "#dddddd",
        "selectTechniquesAcrossTactics": True,
        "metadata": [
            {"name": "repo", "value": "kql-threat-hunting-lab"},
            {"name": "attack_version", "value": model["version"]},
            {"name": "detections_total", "value": str(len(detections))},
            {"name": "detections_passing", "value": str(sum(1 for r in results.values() if r["passed"]))},
        ],
    }
    layer_path = config.COVERAGE_DIR / "attack-layer.json"
    layer_path.write_text(json.dumps(layer, indent=2) + "\n", encoding="utf-8")

    # ---- COVERAGE.md ----
    tactic_order = list(model["tactics"].keys())
    by_tactic: dict[str, list[tuple[str, list[dict]]]] = {}
    for technique_id, dets in covered.items():
        technique = model["techniques"].get(technique_id)
        if not technique:
            continue
        for shortname in technique["tactics"]:
            by_tactic.setdefault(shortname, []).append((technique_id, dets))

    lines = ["# COVERAGE.md", "",
             "**Generated** by `make coverage` from `RESULTS.md` -- do not edit.",
             f"Last generated {datetime.now(UTC).strftime('%Y-%m-%d %H:%M:%SZ')}.", "",
             f"- ATT&CK Enterprise **v{model['version']}**",
             f"- Detections: **{len(detections)}**, "
             f"passing a real-data test: **{sum(1 for r in results.values() if r['passed'])}**",
             f"- Techniques covered: **{len(covered)}**",
             f"- Tactics touched: **{len(by_tactic)}** of {len(model['tactics'])} Enterprise tactics",
             "",
             "> A technique appears here ONLY if a detection claiming it has a test that "
             "produced its required hits on real events from the pinned datasets. Nothing "
             "on this page is hand-maintained.",
             "",
             "> **Scope warning.** These are public *attack-simulation* datasets, not "
             "production telemetry. \"Covered\" means the query fires on the recorded "
             "attack; it does not mean the rule would survive a real estate's noise, nor "
             "that it catches variants absent from these captures. Read each detection's "
             "`known_blind_spots`.",
             ""]

    lines.append("## Coverage by tactic")
    lines.append("")
    for shortname in tactic_order:
        if shortname not in by_tactic:
            continue
        tactic = model["tactics"][shortname]
        entries = sorted({(t, tuple(d["name"] for d in ds)) for t, ds in by_tactic[shortname]})
        lines.append(f"### {tactic['name']} ({tactic['id']})")
        lines.append("")
        lines.append("| Technique | Name | Passing detections |")
        lines.append("|---|---|---|")
        for technique_id, det_names in entries:
            technique = model["techniques"][technique_id]
            lines.append(f"| [{technique_id}]({technique['url']}) | {technique['name']} | "
                         f"{'; '.join(det_names)} |")
        lines.append("")

    lines.append("## Detections and their techniques")
    lines.append("")
    lines.append("| Detection | Severity | Techniques | TP hits | Cross-dataset | Runtime |")
    lines.append("|---|---|---|---:|---:|---:|")
    for detection in sorted(detections, key=lambda d: d["name"]):
        result = results.get(detection["name"], {})
        lines.append(
            f"| {detection['name']} | {detection['severity']} | "
            f"{', '.join(detection['techniques'])} | {result.get('tp_hits', 0)} | "
            f"{result.get('cross_datasets', 0)} | {result.get('runtime', 0):.3f}s |"
        )
    lines.append("")
    (config.COVERAGE_DIR / "COVERAGE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # ---- GAPS.md ----
    manifest_path = config.DATA_DIR / "MANIFEST.json"
    dataset_techniques: dict[str, list[str]] = {}
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        for entry in manifest["datasets"]:
            for technique_id in entry.get("techniques_meta", []):
                dataset_techniques.setdefault(str(technique_id), []).append(entry["dataset_id"])

    gap_lines = ["# GAPS.md", "",
                 "**Generated** by `make coverage` -- do not edit.",
                 f"Last generated {datetime.now(UTC).strftime('%Y-%m-%d %H:%M:%SZ')}.", "",
                 "Techniques that the ingested datasets claim to contain but which no "
                 "passing detection covers. This is the honest to-do list.", "",
                 "> Upstream dataset metadata was authored against a much older ATT&CK "
                 "release (OTRF's last commit is 2023-09-20), so some claimed IDs are "
                 "revoked or deprecated in "
                 f"v{model['version']}. Those are listed separately rather than silently dropped.",
                 ""]

    uncovered_live: list[tuple[str, str, list[str]]] = []
    stale_ids: list[tuple[str, str, list[str]]] = []
    for technique_id, datasets in sorted(dataset_techniques.items()):
        if technique_id in covered:
            continue
        if technique_id in model["techniques"]:
            uncovered_live.append(
                (technique_id, model["techniques"][technique_id]["name"], sorted(set(datasets)))
            )
        elif technique_id in model["revoked"]:
            replacement = model["revoked"][technique_id] or "(none)"
            stale_ids.append((technique_id, f"REVOKED -> {replacement}", sorted(set(datasets))))
        elif technique_id in model["deprecated"]:
            stale_ids.append((technique_id, "DEPRECATED", sorted(set(datasets))))
        else:
            stale_ids.append((technique_id, "NOT IN THIS ATT&CK VERSION", sorted(set(datasets))))

    gap_lines.append(f"## Uncovered techniques present in the data ({len(uncovered_live)})")
    gap_lines.append("")
    if uncovered_live:
        gap_lines.append("| Technique | Name | Datasets that contain it |")
        gap_lines.append("|---|---|---|")
        for technique_id, name, datasets in uncovered_live:
            gap_lines.append(f"| [{technique_id}]({model['techniques'][technique_id]['url']}) | "
                             f"{name} | {', '.join(datasets[:4])}"
                             f"{' ...' if len(datasets) > 4 else ''} |")
    else:
        gap_lines.append("None: every live technique claimed by the ingested data has a "
                         "passing detection.")
    gap_lines.append("")

    gap_lines.append(f"## Claimed by dataset metadata but stale in v{model['version']} "
                     f"({len(stale_ids)})")
    gap_lines.append("")
    gap_lines.append("These need no detection; they are listed so the mismatch between the "
                     "datasets' ATT&CK vintage and the pinned version stays visible.")
    gap_lines.append("")
    if stale_ids:
        gap_lines.append("| Claimed ID | Status | Datasets |")
        gap_lines.append("|---|---|---|")
        for technique_id, status, datasets in stale_ids:
            gap_lines.append(f"| {technique_id} | {status} | {', '.join(datasets[:4])}"
                             f"{' ...' if len(datasets) > 4 else ''} |")
    else:
        gap_lines.append("None.")
    gap_lines.append("")

    # Detections that exist but did not pass
    not_passing = [d for d in detections
                   if not (results.get(d["name"], {}).get("passed"))]
    gap_lines.append(f"## Detections without a passing test ({len(not_passing)})")
    gap_lines.append("")
    if not_passing:
        gap_lines.append("| Detection | Status | Techniques |")
        gap_lines.append("|---|---|---|")
        for detection in sorted(not_passing, key=lambda d: d["name"]):
            gap_lines.append(f"| {detection['name']} | {detection['status']} | "
                             f"{', '.join(detection['techniques'])} |")
    else:
        gap_lines.append("None: every detection in this repo has at least one passing "
                         "real-data test.")
    gap_lines.append("")
    (config.COVERAGE_DIR / "GAPS.md").write_text("\n".join(gap_lines) + "\n", encoding="utf-8")

    print(f"ATT&CK v{model['version']}")
    print(f"  techniques covered : {len(covered)}")
    print(f"  tactics touched    : {len(by_tactic)}")
    print(f"  uncovered in data  : {len(uncovered_live)}")
    print(f"  stale claimed IDs  : {len(stale_ids)}")
    print("\nwrote coverage/attack-layer.json, coverage/COVERAGE.md, coverage/GAPS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
